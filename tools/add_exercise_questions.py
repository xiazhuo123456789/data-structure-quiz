def main():
    data = json.loads(BANK.read_text(encoding="utf-8"))
    data["questions"] = [q for q in data["questions"] if q.get("set") != "exercise"]
    chapters = [c for c in data.get("chapters", []) if c.get("no") != 0]
    chapters.insert(0, {"no": 0, "title": "随堂练习"})
    data["chapters"] = chapters
    data["questions"].extend(Q)
    data["meta"]["count"] = len(data["questions"])
    data["meta"]["title"] = "数据结构（C语言版）第1—5章习题册 · 含随堂练习"
    data["meta"]["source"] = "数据结构（C语言版）第1-5章习题册.docx + 课堂随堂练习"
    BANK.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("总题数", len(data["questions"]), "随堂练习", len(Q))
    from collections import Counter
    print(Counter(q["type"] for q in Q))


if __name__ == "__main__":
    main()
